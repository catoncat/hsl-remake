def _path(*keys: str) -> Callable[[dict], object]:
    def get(unit: dict):
        value = unit
        for key in keys:
            if not isinstance(value, dict) or key not in value:
                return None
            value = value[key]
        return value
    return get


def _equipment(slot: str) -> Callable[[dict], int]:
    def get(unit: dict) -> int:
        return next((int(e['item_code']) for e in unit.get('equipment', []) if e.get('slot') == slot), 0)
    return get


def _dead_message(unit: dict):
    """The death-line ids the remake speaks from (own `dead_message`, else the PLAYERS pair of
    aftermath.json); compared with the nonzero halves of +0x14 as a set — the remake list does not
    keep which half an id sat in (obj_Data8 374 is the low half, a PLAYERS pair is hi／lo)."""
    ids = unit['extra'].get('dead_message_ids')
    return None if ids is None else sorted(int(i) for i in ids)


def _mode(unit: dict):
    """player_mode; a curated scenario without one has only the role's side (compared as +0x28 & 0x70000)."""
    return unit['player_mode'] if 'player_mode' in unit else {'side': unit['extra']['side_mask']}


