def _capability(unit: dict) -> int:
    extra, traversal = unit['extra'], unit.get('traversal', {})
    return (int(extra.get('status_capability_flags', 0)) | (2 if unit.get('no_attack') else 0)
            | (1 if traversal.get('flying') else 0) | (0x10 if traversal.get('no_block') else 0)
            | (0x200 if extra.get('double_attack') else 0) | (0x400 if extra.get('move_magic_use') else 0)
            | (4 if unit.get('undead') else 0) | (8 if unit.get('side_swapped') else 0))


def _half(getter: Callable[[dict], object], default_zero: bool = False) -> Callable[[dict], object]:
    def get(unit: dict):
        value = getter(unit)
        return 0 if value is None and default_zero else value
    return get


@dataclasses.dataclass(frozen=True)
class Field:
    name: str
    offset: int
    fmt: str                        # u32 i32 u16 i16, or items／special／magic (decoded lists)
    remake: Callable[[dict], object] | None
    reading: str
    size: int = 0

    @property
    def width(self) -> int:
        return self.size or {'u32': 4, 'i32': 4, 'u16': 2, 'i16': 2}[self.fmt]


def _field(name, offset, fmt, remake, reading, size=0) -> Field:
    return Field(name, offset, fmt, remake, reading, size)


